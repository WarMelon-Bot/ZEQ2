#!/usr/bin/env python3
"""Generate the runtime GL dispatch table used by the renderer backends.

The legacy renderer addressed OpenGL through `qglFoo` macros that expanded
straight to `glFoo`.  To be able to run the very same renderer front end on a
Vulkan backend, those macros now index a small table of function pointers that
is filled in by whichever backend is active.  This script keeps the generated
list of functions in sync with the macro names in qgl.h.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
QGL_H = ROOT / "Engine" / "renderer" / "qgl.h"
OUT = ROOT / "Engine" / "renderer" / "qgl_dispatch.h"

MACRO = re.compile(r"^#define\s+qgl(\w+)\s+QGL_DISPATCH_FN\((\w+)\)\s*$")


def main() -> int:
    names = []
    for line in QGL_H.read_text().splitlines():
        match = MACRO.match(line)
        if match and match.group(1) == match.group(2):
            if match.group(2) not in names:
                names.append(match.group(2))

    if not names:
        print("error: no qgl dispatch macros found in qgl.h", file=sys.stderr)
        return 1

    lines = [
        "/* Generated by Source/Tools/generate_qgl_dispatch.py -- do not edit. */",
        "#ifndef __QGL_DISPATCH_H",
        "#define __QGL_DISPATCH_H",
        "",
        "/* Every core GL entry point the renderer can call. */",
        "#define QGL_DISPATCH_FUNCS(X) \\",
    ]
    for index, name in enumerate(names):
        suffix = " \\" if index + 1 < len(names) else ""
        lines.append(f"\tX({name}){suffix}")
    arb_names = []
    for line in QGL_H.read_text().splitlines():
        if not line.startswith("extern ") or "APIENTRYP qgl" not in line:
            continue
        match = re.search(r"\b(qgl\w+)\b", line)
        if match and match.group(1) not in arb_names:
            arb_names.append(match.group(1))

    lines += [
        "",
        "/* Extension entry points, also switched between the two backends. */",
        "#define QGL_ARB_FUNCS(X) \\",
    ]
    for index, name in enumerate(arb_names):
        suffix = " \\" if index + 1 < len(arb_names) else ""
        lines.append(f"\tX({name}){suffix}")
    lines += [
        "",
        "typedef enum {",
        "#define QGL_DISPATCH_ENUM(name) QGLFN_##name,",
        "\tQGL_DISPATCH_FUNCS(QGL_DISPATCH_ENUM)",
        "#undef QGL_DISPATCH_ENUM",
        "#define QGL_ARB_ENUM(name) QGLFNARB_##name,",
        "\tQGL_ARB_FUNCS(QGL_ARB_ENUM)",
        "#undef QGL_ARB_ENUM",
        "\tQGLFN_COUNT",
        "} qglFunction_t;",
        "",
        "typedef union {",
        "\tvoid *object;",
        "\tvoid (*function)(void);",
        "} qglFunctionPointer;",
        "",
        "extern qglFunctionPointer qgl_dispatch_table[QGLFN_COUNT];",
        "",
        "/* Cast through a generic function pointer: GCC/Clang accept this for",
        "   OpenGL entry points, whose prototypes live in SDL_opengl.h. */",
        "#define QGL_DISPATCH_FN(name) ((__typeof__(&gl##name))qgl_dispatch_table[QGLFN_##name].object)",
        "",
        "void QGL_InitGLDispatch( void );",
        "void QGL_InitVulkanDispatch( void );",
        "void QGL_SelectBackend( qboolean vulkan );",
        "qboolean QGL_UsingVulkan( void );",
        "const char *QGL_BackendName( void );",
        "",
        "void QGL_SetVulkanARBDispatch( void );",
        "void QGL_ClearARBDispatch( void );",
        "",
        "#ifdef HAVE_VULKAN",
        "void Vkqgl_InstallDispatch( qglFunctionPointer *table );",
        "qboolean Vkqgl_Init( void );",
        "void Vkqgl_Shutdown( void );",
        "void Vkqgl_Present( void );",
        "qboolean Vkqgl_Available( void );",
        "#endif",
        "",
        "#endif",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT.parent.parent)} ({len(names)} functions)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
